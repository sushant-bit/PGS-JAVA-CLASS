package Week2;

public class Operators {
    public static void main(String[] args) {
        int a=10;
        int b=20;

        b=++a;
        System.out.println(a);
        System.out.println(b);

        int c =20;
        int d=c++;

        System.out.println(c);
        System.out.println(d);
    }
}
